import fs from 'fs';
import path from 'path';

// 1. Figma API 정보 및 토큰 로드 (zibis_pass.env 또는 process.env.FIGMA_TOKEN)
const FILE_KEY = 'jbY7UQpEef51snW6FzFSfg'; // zibis.co.kr 피그마 파일 키

function getFigmaToken() {
  if (process.env.FIGMA_TOKEN) {
    return process.env.FIGMA_TOKEN;
  }
  const envPath = '/Users/zibis/Desktop/zibis_pass.env';
  if (fs.existsSync(envPath)) {
    const content = fs.readFileSync(envPath, 'utf8');
    const match = content.match(/figd_[a-zA-Z0-9_-]+/g);
    if (match && match.length > 0) {
      return match[match.length - 1].trim();
    }
  }
  throw new Error('Figma API Token을 찾을 수 없습니다.');
}

function rgbaToString(color) {
  if (!color) return 'transparent';
  const r = Math.round(color.r * 255);
  const g = Math.round(color.g * 255);
  const b = Math.round(color.b * 255);
  const a = color.a !== undefined ? color.a : 1;
  if (a < 1) {
    return `rgba(${r}, ${g}, ${b}, ${a.toFixed(2)})`;
  }
  const toHex = (n) => n.toString(16).padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

function sanitizeVarName(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9-_]/g, '-')
    .replace(/-+/g, '-');
}

// 피그마 노드 노드를 재귀 탐색하여 스타일 및 컬러 추출 (file_content:read 권한 활용)
function extractTokensFromNode(node, tokens = {}) {
  if (!node) return tokens;

  if (node.fills && Array.isArray(node.fills)) {
    for (const fill of node.fills) {
      if (fill.type === 'SOLID' && fill.color) {
        const name = sanitizeVarName(node.name || 'color');
        if (
          name.includes('color') ||
          name.includes('theme') ||
          name.includes('bg') ||
          name.includes('text') ||
          name.includes('brand') ||
          name.includes('azure') ||
          name.includes('storm') ||
          name.includes('gray')
        ) {
          tokens[name] = rgbaToString(fill.color);
        }
      }
    }
  }

  if (node.children && Array.isArray(node.children)) {
    for (const child of node.children) {
      extractTokensFromNode(child, tokens);
    }
  }
  return tokens;
}

async function main() {
  console.log('====================================================');
  console.log('🎨 Figma 변수 -> zibis.co.kr 토큰 동기화 시작');
  console.log('====================================================');

  const token = getFigmaToken();
  let cssTokens = {};

  // 1. Variables API 시도 (Enterprise 권한 필요)
  const varUrl = `https://api.figma.com/v1/files/${FILE_KEY}/variables/local`;
  console.log(`📡 Figma Variables API 호출 시도...`);
  const varRes = await fetch(varUrl, { headers: { 'X-Figma-Token': token } });

  if (varRes.ok) {
    const { meta } = await varRes.json();
    const variables = meta.variables || {};
    for (const v of Object.values(variables)) {
      const varName = sanitizeVarName(v.name);
      const modeValues = Object.values(v.valuesByMode);
      if (modeValues.length === 0) continue;
      const rawVal = modeValues[0];
      if (v.resolvedType === 'COLOR') {
        cssTokens[varName] = rgbaToString(rawVal);
      } else if (v.resolvedType === 'FLOAT') {
        cssTokens[varName] = typeof rawVal === 'number' ? `${rawVal}px` : rawVal;
      } else {
        cssTokens[varName] = String(rawVal);
      }
    }
    console.log(`✅ Variables API로 ${Object.keys(cssTokens).length}개 변수 추출 완료.`);
  } else {
    // 2. Standard File Styles API로 폴백 (file_content:read 권한 사용)
    console.log(`ℹ️ Variables API 권한 제한 (403) -> Standard File API (file_content:read)로 자동 전환합니다.`);
    const fileUrl = `https://api.figma.com/v1/files/${FILE_KEY}`;
    console.log(`📡 Figma File API 호출중: FileKey=${FILE_KEY}`);
    const fileRes = await fetch(fileUrl, { headers: { 'X-Figma-Token': token } });

    if (!fileRes.ok) {
      const errText = await fileRes.text();
      throw new Error(`Figma API 호출 실패 (${fileRes.status}): ${errText}`);
    }

    const fileData = await fileRes.json();
    const styles = fileData.styles || {};
    console.log(`✅ Figma File 스캔 완료: Styles ${Object.keys(styles).length}개 스캔 완료.`);

    // 피그마 노드 구조에서 대표 컬러 및 스타일 수집
    extractTokensFromNode(fileData.document, cssTokens);

    // 핵심 기본 디자인 토큰 보정 (Desert Storm, Science Blue, Cod Gray 등)
    cssTokens['theme-light'] = cssTokens['theme-light'] || '#f9f9f7';
    cssTokens['theme-dark'] = cssTokens['theme-dark'] || '#111111';
    cssTokens['color-azure-39'] = cssTokens['color-azure-39'] || '#036cc5';
    cssTokens['color-grey-97'] = cssTokens['color-grey-97'] || '#f9f9f7';
    cssTokens['color-grey-11'] = cssTokens['color-grey-11'] || '#111111';
    cssTokens['font-size-10'] = '10px';
    cssTokens['font-size-12'] = '12px';
    cssTokens['font-size-14'] = '14px';
    cssTokens['font-size-36'] = '36px';
    cssTokens['font-size-100'] = '100px';
  }

  let cssContent = `/* 🎨 Automatically generated by sync-figma-tokens.mjs from Figma */\n:root {\n`;
  for (const [k, v] of Object.entries(cssTokens)) {
    cssContent += `  --${k}: ${v};\n`;
  }
  cssContent += `}\n`;

  const outputPath = path.resolve('src/app/tokens.css');
  fs.writeFileSync(outputPath, cssContent, 'utf8');

  console.log(`🎉 성공적으로 토큰 생성이 완료되었습니다: ${outputPath}`);
}

main().catch((err) => {
  console.error('❌ 동기화 실패:', err);
  process.exit(1);
});
