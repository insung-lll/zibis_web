import fs from 'fs';
import path from 'path';

// 1. Figma API 정보 및 토큰 로드 (zibis_pass.env 또는 process.env.FIGMA_TOKEN)
const FILE_KEY = 'jbY7UQpEef51snW6FzFSfg'; // zibis.co.kr 피그마 파일 키

function getFigmaToken() {
  if (process.env.FIGMA_TOKEN) {
    return process.env.FIGMA_TOKEN;
  }
  const envPath = '/Users/zibis/Desktop/zibis_pass.env';
  if (fs.existsSync(envPath)) {
    const content = fs.readFileSync(envPath, 'utf8');
    const match = content.match(/Antigravity assistant api=(.*)/);
    if (match && match[1]) {
      return match[1].trim();
    }
  }
  throw new Error('Figma API Token을 찾을 수 없습니다.');
}

function rgbaToString(color) {
  if (!color) return 'transparent';
  const r = Math.round(color.r * 255);
  const g = Math.round(color.g * 255);
  const b = Math.round(color.b * 255);
  const a = color.a !== undefined ? color.a : 1;
  if (a < 1) {
    return `rgba(${r}, ${g}, ${b}, ${a.toFixed(2)})`;
  }
  const toHex = (n) => n.toString(16).padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

function sanitizeVarName(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9-_]/g, '-')
    .replace(/-+/g, '-');
}

async function main() {
  console.log('====================================================');
  console.log('🎨 Figma 변수 -> zibis.co.kr 토큰 동기화 시작');
  console.log('====================================================');

  const token = getFigmaToken();
  const url = `https://api.figma.com/v1/files/${FILE_KEY}/variables/local`;

  console.log(`📡 Figma API 호출: FileKey=${FILE_KEY}`);
  const res = await fetch(url, {
    headers: { 'X-Figma-Token': token }
  });

  if (!res.ok) {
    const errText = await res.text();
    throw new Error(`Figma API 호출 실패 (${res.status}): ${errText}`);
  }

  const { meta } = await res.json();
  const variables = meta.variables || {};
  const collections = meta.variableCollections || {};

  console.log(`✅ 총 ${Object.keys(variables).length}개의 변수 획득 완료.`);

  let cssContent = `/* 🎨 Automatically generated by sync-figma-tokens.mjs from Figma */\n:root {\n`;

  for (const v of Object.values(variables)) {
    const varName = sanitizeVarName(v.name);
    const modeValues = Object.values(v.valuesByMode);
    if (modeValues.length === 0) continue;
    const rawVal = modeValues[0];

    let cssValue = '';
    if (v.resolvedType === 'COLOR') {
      cssValue = rgbaToString(rawVal);
    } else if (v.resolvedType === 'FLOAT') {
      cssValue = typeof rawVal === 'number' ? `${rawVal}px` : rawVal;
    } else {
      cssValue = String(rawVal);
    }

    cssContent += `  --${varName}: ${cssValue};\n`;
  }

  cssContent += `}\n`;

  const outputPath = path.resolve('src/app/tokens.css');
  fs.writeFileSync(outputPath, cssContent, 'utf8');

  console.log(`🎉 성공적으로 토큰 생성이 완료되었습니다: ${outputPath}`);
}

main().catch((err) => {
  console.error('❌ 동기화 실패:', err);
  process.exit(1);
});
